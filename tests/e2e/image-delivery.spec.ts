import { expect, test } from "@playwright/test";
import { createHash } from "node:crypto";
import { mkdir, rm, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { pngBytes } from "../helpers/image-fixtures";

const dataDir = process.env.DATA_DIR;

function attemptId(index: number): string {
  return `00000000-0000-4000-8000-${index.toString(16).padStart(12, "0")}`;
}

function entry(
  productId: string,
  index: number,
  bytes: Buffer,
  width = 32,
  height = 32,
): { filename: string; manifest: Record<string, unknown> } {
  const id = attemptId(index);
  const filename = `${productId}-${id}.png`;
  const sha256 = createHash("sha256").update(bytes).digest("hex");
  const attempt = {
    attemptId: id,
    startedAt: new Date().toISOString(),
    finishedAt: new Date().toISOString(),
    status: "succeeded",
    filename,
    format: "png",
    mediaType: "image/png",
    sizeBytes: bytes.byteLength,
    sha256,
    width,
    height,
    cost: { kind: "unknown" },
    error: null,
  };
  return {
    filename,
    manifest: {
      active: {
        attemptId: id,
        filename,
        format: "png",
        mediaType: "image/png",
        sizeBytes: bytes.byteLength,
        sha256,
        width,
        height,
        publishedAt: new Date().toISOString(),
      },
      attempts: [attempt],
    },
  };
}

async function seedDeliveryState(): Promise<void> {
  if (!dataDir) throw new Error("Missing DATA_DIR for the E2E web server.");
  const imagesDir = join(dataDir, "images");
  await mkdir(imagesDir, { recursive: true });

  const good = pngBytes(32, 32);
  const garbage = Buffer.from("this is not a png");
  const p01 = entry("P01", 300, good);
  const p02 = entry("P02", 301, garbage);
  const products: Record<string, unknown> = {};
  for (let index = 1; index <= 24; index += 1) {
    const productId = `P${String(index).padStart(2, "0")}`;
    if (productId === "P01") products[productId] = p01.manifest;
    else if (productId === "P02") products[productId] = p02.manifest;
    else products[productId] = { active: null, attempts: [] };
  }
  await writeFile(join(imagesDir, p01.filename), good);
  await writeFile(join(imagesDir, p02.filename), garbage);
  await writeFile(
    join(imagesDir, "manifest.json"),
    `${JSON.stringify({ version: 1, updatedAt: new Date().toISOString(), products }, null, 2)}\n`,
  );
}

async function clearDeliveryState(): Promise<void> {
  if (!dataDir) return;
  await rm(join(dataDir, "images"), { recursive: true, force: true });
}

test.beforeEach(clearDeliveryState);
test.afterAll(clearDeliveryState);

test("serves saved images in the catalog and falls back to placeholders", async ({
  page,
}) => {
  await seedDeliveryState();
  await page.goto("/shop");

  const p01 = page.locator('[data-product-id="P01"]');
  await expect(p01.locator("img")).toBeVisible();
  await expect(p01.locator("img")).toHaveAttribute(
    "src",
    /\/api\/images\/P01\?v=[0-9a-f]{16}/,
  );

  const p02 = page.locator('[data-product-id="P02"]');
  await expect(
    p02.getByRole("img", { name: "Placeholder image for Nova Mechanical Keyboard" }),
  ).toBeVisible();
  await expect(p02.locator("img")).toHaveCount(0);
});

test("delivers only validated product images", async ({ request }) => {
  await seedDeliveryState();

  const good = await request.get("/api/images/P01");
  expect(good.status()).toBe(200);
  expect(good.headers()["content-type"]).toBe("image/png");
  expect(good.headers()["cache-control"]).toBe("no-store");

  expect((await request.get("/api/images/P02")).status()).toBe(404);
  expect((await request.get("/api/images/P99")).status()).toBe(404);
  expect((await request.get("/api/images/..%2F..%2Fpackage.json")).status()).toBe(404);
  expect((await request.get("/api/images/..%5C..%5Cpackage.json")).status()).toBe(404);
  expect(
    (await request.get("/api/images/P01%2F..%2F..%2Fpackage.json")).status(),
  ).toBe(404);
});

test("an old versioned URL still serves the regenerated bytes", async ({ request }) => {
  await seedDeliveryState();
  const before = await request.get("/api/images/P01?v=0000000000000000");
  expect(before.status()).toBe(200);
  const firstEtag = before.headers()["etag"];
  expect(firstEtag).toBeTruthy();

  const good = pngBytes(96, 96);
  const p01 = entry("P01", 302, good, 96, 96);
  const manifestPath = join(dataDir ?? "", "images", "manifest.json");
  const raw = JSON.parse(
    await (await import("node:fs/promises")).readFile(manifestPath, "utf8"),
  ) as { products: Record<string, unknown> };
  raw.products.P01 = p01.manifest;
  await writeFile(join(dataDir ?? "", "images", p01.filename), good);
  await writeFile(manifestPath, `${JSON.stringify(raw, null, 2)}\n`);

  const after = await request.get(`/api/images/P01?v=${firstEtag}`);
  expect(after.status()).toBe(200);
  expect(after.headers()["etag"]).not.toBe(firstEtag);
  expect(Buffer.from(await after.body()).length).toBe(good.byteLength);
});

test("uses the same validated image on the detail page", async ({ page }) => {
  await seedDeliveryState();

  await page.goto("/shop/products/orbit-wireless-headphones");
  await expect(
    page.getByRole("img", { name: "Orbit Wireless Headphones" }),
  ).toBeVisible();

  await page.goto("/shop/products/nova-mechanical-keyboard");
  await expect(
    page.getByRole("img", { name: "Placeholder image for Nova Mechanical Keyboard" }),
  ).toBeVisible();
});
